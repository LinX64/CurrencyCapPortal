#!/usr/bin/env python3
"""Generate the Swift test vectors for the sealed channel with the Python reference sealer.

Deterministic: fixed TEST keys (never the production keys), fixed `issued`, counter-derived nonces, so the
fixture is reproducible byte for byte and tests/test_sealed_vectors.py can detect a stale fixture.

Usage: python tests/make_sealed_vectors.py [path/to/sealed-vectors.json]
Default output: ../Gheymat/ios/GheymatTests/Fixtures/sealed-vectors.json next to this repo.
"""
from __future__ import annotations

import base64
import hashlib
import json
import os
import sys
from pathlib import Path

from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "tools"))
import gheymat_seal as gs  # noqa: E402

DEFAULT_OUT = Path(__file__).resolve().parents[2] / "Gheymat" / "ios" / "GheymatTests" / "Fixtures" / "sealed-vectors.json"
TEST_PAYLOAD_KEY = bytes(range(101, 133))
TEST_SIGNING_SEEDS = {1: bytes(range(200, 232)), 2: bytes(range(10, 42))}
ISSUED = 1792051212
OPAQUE_PATHS = ["health", "v1/latest", "v1/history/usd"]

HEALTH = {"ok": True, "lastFetchAt": "2026-10-15T08:00:12Z", "ageSeconds": 12.3, "consecutiveFailures": 0,
          "proxyPool": {"size": 5, "healthy": 2, "inUse": None, "enabled": False, "paidConfigured": False},
          "seq": 12, "pollSeconds": 30, "tradingHours": True, "blockedReason": None, "stale": False,
          "staleSince": None, "signals": {}}
LATEST = {"seq": 1792000000, "fetchedAt": "2026-10-15T08:00:12Z", "sourceModified": "October 15, 2026 11:30",
          "source": "bonbast", "flags": ["static"], "rates": [
              {"code": "usd", "kind": "currency", "unit": 1, "quote": "toman", "buy": 265000, "sell": 265200,
               "price": None, "en": "US Dollar", "fa": "دلار آمریکا", "flag": "🇺🇸"},
              {"code": "ounce", "kind": "gold", "unit": 1, "quote": "usd", "buy": None, "sell": None,
               "price": 4321.5, "en": "Gold Ounce", "fa": "اونس طلا", "flag": ""}]}
INSTRUMENTS = [{"code": "usd", "bonbast_key": "usd", "kind": "currency", "unit": 1, "quote": "toman",
                "en": "US Dollar", "fa": "دلار آمریکا", "flag": "🇺🇸"},
               {"code": "eur", "bonbast_key": "eur", "kind": "currency", "unit": 1, "quote": "toman",
                "en": "Euro", "fa": "یورو", "flag": "🇪🇺"}]


class _DeterministicOS:
    environ = os.environ

    def __init__(self) -> None:
        self.counter = 0

    def urandom(self, n: int) -> bytes:
        self.counter += 1
        return hashlib.sha256(b"gheymat-test-nonce:" + self.counter.to_bytes(4, "big")).digest()[:n]


def compact(obj) -> str:
    return json.dumps(obj, ensure_ascii=False, separators=(",", ":"))


def make_vectors() -> dict:
    real_os, gs.os = gs.os, _DeterministicOS()
    try:
        return _make_vectors()
    finally:
        gs.os = real_os


def _make_vectors() -> dict:
    signing = {kid: Ed25519PrivateKey.from_private_bytes(seed) for kid, seed in TEST_SIGNING_SEEDS.items()}
    sealers = {kid: gs.Sealer(TEST_PAYLOAD_KEY, key, kid=kid) for kid, key in signing.items()}
    current = sealers[1]

    def vector(name: str, logical: str, env: dict, plaintext=None) -> dict:
        return {"name": name, "logical": logical, "issued": env["issued"], "kid": env["kid"],
                "plaintext": compact(plaintext) if plaintext is not None else None,
                "envelope": json.dumps(env, separators=(",", ":"))}

    latest = current.seal("v1/latest", LATEST, issued=ISSUED)
    tampered_ct = bytearray(gs.unb64(latest["ciphertext"]))
    tampered_ct[0] ^= 0x01
    nonce = gs.unb64(latest["nonce"])
    resigned = {**latest, "ciphertext": gs.b64(bytes(tampered_ct)),
                "sig": gs.b64(signing[1].sign(gs.header("v1/latest", ISSUED, nonce, 1) + bytes(tampered_ct)))}
    stale_sig = {**latest, "ciphertext": gs.b64(bytes(tampered_ct))}
    vectors = [
        vector("health", "health", current.seal("health", HEALTH, issued=ISSUED), HEALTH),
        vector("latest", "v1/latest", latest, LATEST),
        vector("instruments", "v1/instruments", current.seal("v1/instruments", INSTRUMENTS, issued=ISSUED), INSTRUMENTS),
        vector("tampered-resigned", "v1/latest", resigned),
        vector("bad-signature", "v1/latest", stale_sig),
        vector("next-key", "v1/latest", sealers[2].seal("v1/latest", LATEST, issued=ISSUED), LATEST),
    ]
    public_keys = {str(kid): gs.b64(key.public_key().public_bytes_raw()) for kid, key in signing.items()}
    return {
        "note": "TEST keys only (deterministic seeds, never the production keys). Generated by "
                "CurrencyCapPortal/tests/make_sealed_vectors.py with the reference sealer tools/gheymat_seal.py.",
        "version": gs.VERSION,
        "payloadKey": base64.b64encode(TEST_PAYLOAD_KEY).decode("ascii"),
        "signingPublicKeys": public_keys,
        "opaquePaths": {logical: current.opaque_path(logical) for logical in OPAQUE_PATHS},
        "vectors": vectors,
    }


def render(fixture: dict) -> str:
    return json.dumps(fixture, ensure_ascii=False, indent=2) + "\n"


def main() -> int:
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_OUT
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(render(make_vectors()), encoding="utf-8")
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
